"""Generate js/0125_v214_coh3-indirect-generated.js from the CoH3 game JSON (weapon_bag data).

python3 -I tools/coh3_indirect.py coh3_american.json coh3_german.json

Per indirect unit it writes the raw weapon numbers (damage, penetration, AoE falloff averaged over a
squad spread of SPREAD m, max members per squad, scatter). Turn-based figures (shells per attack,
reload turns, member cap used in play) live in V214.TURN in js/0140_v200_*.js, not here.
"""
import json, os, sys

SPREAD = 5.0   # m: radius a squad occupies inside one hex (1 hex = 7 m)
UNITS = {   # game key -> CoH3 weapon id
    'blue': {'mortar': '81mm_mortar_us', 'pack75': '75mm_pack_howitzer_us', 'scott': '75mm_howitzer_barrage_scott_us',
             'howitzer': '105mm_howitzer_normal_us', 'priest': '105mm_howitzer_priest_us', 'whizbang': '180mm_rocket_barrage_whizbang_us'},
    'red': {'mortar': '81mm_mortar_ger', 'howitzer': '150mm_hummel_ger', 'hummel': '150mm_hummel_ger', 'wespe': '105mm_wespe_ger',
            'obice210': 'obice_210_howitzer_ger', 'nebel': '150mm_nebelwerfer_he_ger'},
}


def bags(d, out):
    for k, v in d.items():
        if isinstance(v, dict):
            if 'weapon_bag' in v: out[k] = v['weapon_bag']
            else: bags(v, out)
    return out


def falloff_avg(a):
    band = [(a['distance'][x], a['damage'][x]) for x in ('near', 'mid', 'far')]
    R = a['area_info'].get('outer_radius') or band[2][0]
    prev, s = 0.0, 0.0
    for i, (e, f) in enumerate(band):
        e = min(e if i < 2 else min(e, R), SPREAD)
        if e > prev: s += f * (e * e - prev * prev) / (SPREAD * SPREAD); prev = e
    return round(s, 3)


def main(us_path, de_path):
    W = {'blue': bags(json.load(open(us_path))['weapon'], {}), 'red': bags(json.load(open(de_path))['weapon'], {})}
    out = {'blue': {}, 'red': {}}
    for tm, m in UNITS.items():
        for key, wid in m.items():
            b = W[tm][wid]; a = b['area_effect']; sc = b['scatter']
            out[tm][key] = {'id': wid, 'd': b['damage']['max'], 'pen': b['penetration']['mid'],
                            'aoe': falloff_avg(a), 'maxM': a.get('damage_max_members_per_squad', -1),
                            'sc': [sc['angle_scatter'], sc['distance_scatter_ratio'], sc['distance_scatter_max']]}
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', '0125_v214_coh3-indirect-generated.js')
    with open(dst, 'w', encoding='utf8') as f:
        f.write('  // [v214] CoH3 raw indirect-fire weapons (generated by tools/coh3_indirect.py from the game JSON — re-run instead of editing by hand)\n')
        f.write('  //   d damage, pen penetration, aoe = AoE falloff averaged over a 5 m squad spread, maxM = max members per squad (-1 none),\n')
        f.write('  //   sc = scatter [angle deg, distance ratio, max m]\n')
        f.write('  const COH3_IND = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print('wrote', os.path.normpath(dst))


if __name__ == '__main__':
    main(*sys.argv[1:3])
