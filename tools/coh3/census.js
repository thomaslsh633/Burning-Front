// Census of the downloaded CoH3 data: which categories exist per faction, and which blocks each category uses.
// Feeds the category profiles of docs/data-form-roadmap.md. Writes data/source/coh3/CENSUS.md.
//
// usage: node tools/coh3/census.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RACES } from './fetch.js';
import { records } from '../lib/coh3.js';

const T = v => v === 'True' || v === true;
const num = v => (typeof v === 'number' ? v : 0);

// Weapon blocks that carry a value (one test per module of the planned weapon form).
export const WEAPON_CHECKS = {
  aoe: b => num(b.area_effect?.area_info?.outer_radius) > 0,
  scatter: b => num(b.scatter?.angle_scatter) > 0,
  setup: b => T(b.behaviour?.non_moving_setup),
  burst: b => T(b.burst?.can_burst),
  min_range: b => num(b.range?.min) > 0,
  deflect: b => T(b.deflection?.has_deflection_damage),
  move_fire: b => T(b.moving?.can_fire_while_moving),
  suppression: b => num(b.suppression?.amount) > 0,
  reload: b => num(b.reload?.frequency?.max) > 0,
  target_table: b => (b.target_type_table || []).length > 0,
};

const extName = x => (x.exts || x.squadexts || x).template_reference?.value?.split('\\').pop() ?? '?';

// Category key of a record: weapons use the subcategory (last folder), ebps / sbps the top category.
const weaponCat = p => p[p.length - 2] ?? p[0];
const topCat = p => p[0];

export function census(dir) {
  const load = (kind, race) => JSON.parse(fs.readFileSync(path.join(dir, kind, `${race}.json`), 'utf8'));
  const result = { weapon: {}, ebps: {}, sbps: {}, cats: {} };
  for (const race of RACES) {
    result.cats[race] = {};
    for (const kind of ['weapon', 'ebps', 'sbps']) {
      const data = load(kind, race);
      result.cats[race][kind] = Object.keys(data);
      for (const { path: p, rec } of records(data)) {
        const cat = kind === 'weapon' ? weaponCat(p) : topCat(p);
        const row = (result[kind][cat] ??= { n: 0, races: new Set(), uses: {} });
        row.n++; row.races.add(race);
        if (kind === 'weapon') {
          for (const [k, f] of Object.entries(WEAPON_CHECKS)) { try { if (f(rec.weapon_bag)) row.uses[k] = (row.uses[k] || 0) + 1; } catch { } }
        } else {
          for (const x of rec.extensions || []) { const e = extName(x); row.uses[e] = (row.uses[e] || 0) + 1; }
        }
      }
    }
  }
  return result;
}

function markdown(r, source) {
  const L = [`# CoH3 data census`, ``, `coh3-data \`${source.commit.slice(0, 8)}\` (${source.commit_date}), factions: ${RACES.join(', ')}.`,
    `Generated by \`node tools/coh3/census.js\`; do not edit.`, ``];
  L.push(`## Top-level categories per faction`, ``, `| Faction | weapon | ebps | sbps |`, `| --- | --- | --- | --- |`);
  for (const race of RACES) L.push(`| ${race} | ${r.cats[race].weapon.join(', ')} | ${r.cats[race].ebps.join(', ')} | ${r.cats[race].sbps.join(', ')} |`);
  const keys = Object.keys(WEAPON_CHECKS);
  L.push(``, `## Weapon: records using each block (all factions)`, ``, `| Subcategory | n | ${keys.join(' | ')} |`, `| --- | ---: | ${keys.map(() => '---:').join(' | ')} |`);
  for (const [cat, row] of Object.entries(r.weapon).sort()) L.push(`| ${cat} | ${row.n} | ${keys.map(k => row.uses[k] || 0).join(' | ')} |`);
  for (const kind of ['ebps', 'sbps']) {
    const cats = Object.keys(r[kind]).sort();
    const exts = [...new Set(cats.flatMap(c => Object.keys(r[kind][c].uses)))].sort()
      .filter(e => cats.some(c => (r[kind][c].uses[e] || 0) / r[kind][c].n >= 0.3));
    L.push(``, `## ${kind}: share of records with each extension (≥ 30 % in some category)`, ``,
      `| Extension | ${cats.map(c => `${c} (${r[kind][c].n})`).join(' | ')} |`, `| --- | ${cats.map(() => '---:').join(' | ')} |`);
    for (const e of exts) L.push(`| ${e} | ${cats.map(c => `${Math.round(100 * (r[kind][c].uses[e] || 0) / r[kind][c].n)} %`).join(' | ')} |`);
  }
  return L.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const dir = path.join(root, 'data/source/coh3');
  const source = JSON.parse(fs.readFileSync(path.join(dir, 'SOURCE.json'), 'utf8'));
  fs.writeFileSync(path.join(dir, 'CENSUS.md'), markdown(census(dir), source));
  console.log('wrote data/source/coh3/CENSUS.md');
}
