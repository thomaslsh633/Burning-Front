// Runs the fire-rate conversion over every CoH3 weapon of the four factions + common and writes a review report.
// usage: node tools/import-coh3/fire-rate-report.js   → reports/fire-rate.md, reports/fire-rate.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RACES } from '../coh3/fetch.js';
import { records } from '../lib/coh3.js';
import { fireRate } from './fire-rate.js';
import { loadConfig } from '../lib/config.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const cfg = loadConfig(root).fire;
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/source/coh3/SOURCE.json'), 'utf8'));

const rows = [];
for (const race of RACES) {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/source/coh3/weapon', `${race}.json`), 'utf8'));
  for (const { path: p, rec } of records(data)) {
    const category = p[p.length - 2] ?? p[0];
    if (cfg.skip_categories.some(s => p.includes(s)) || p[0] === 'campaign') continue;
    const bag = rec.weapon_bag;
    rows.push({ race, id: p[p.length - 1], category, class: bag.weapon_class ?? '', damage: ((bag.damage?.min ?? 0) + (bag.damage?.max ?? 0)) / 2,
      ...fireRate(bag, category, cfg, p[p.length - 1]) });
  }
}

// effective rate the game delivers, relative to CoH3 (1 = exact), worst band
for (const r of rows) {
  const eff = b => ['per_use', 'single_shot', 'ability'].includes(r.rule) ? 1
    : r.rule === 'artillery' ? (r.shots_per_turn[b] / (r.reload_turns + 1)) * r.accuracy_scale[b] / r.raw[b]
    : r.damage > 0 ? (r.shots_per_turn[b] * r.damage_per_shot[b]) / (r.raw[b] * r.damage) : r.shots_per_turn[b] / r.raw[b];
  r.rate_error = Math.round(Math.max(...cfg.bands.map(b => Math.abs(eff(b) - 1))) * 1000) / 1000;
}

fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
fs.writeFileSync(path.join(root, 'reports/fire-rate.json'), JSON.stringify({ source: source.commit, config: cfg, weapons: rows }, null, 1) + '\n');

const b3 = o => cfg.bands.map(b => o[b] ?? '—').join(' / ');
const pct = x => `${Math.round(x * 100)} %`;
const L = ['# Fire rate report', '',
  `CoH3 weapons (coh3-data \`${source.commit.slice(0, 8)}\`) converted to whole shots per turn (${cfg.window_seconds} s fire window).`,
  'Generated by `node tools/import-coh3/fire-rate-report.js`; rules in `tools/import-coh3/fire-rate.js`, settings in `data/balance/fire-rate.json`.', '',
  '- **raw**: CoH3 sustained shots in the fire window (bullets for burst weapons), near / mid / far.',
  '- **shots**: whole shots per turn in the game. **damage**: damage per shot in the game.',
  `- **rule**: \`volley\` = whole damage per shot (CoH3 damage ÷ ≤ ${cfg.volley.max_multiplier}) and whole shots, within ${pct(cfg.volley.tolerance)} where possible (× = CoH3 damage ÷ game damage);`,
  '  `single_shot` = once per turn, damage × raw; `artillery` = CoH3 damage per shell, rate rounded up (shells or reload turns),',
  '  accuracy × **acc** so expected damage per turn equals CoH3; `ability` = artillery fired only by abilities; `per_use` = grenade or mine.',
  '- **error**: worst band difference between the game\'s expected damage per turn and CoH3\'s.', ''];

const byRule = {};
for (const r of rows) (byRule[r.rule] ??= []).push(r);
L.push('## Summary by rule', '', '| Rule | weapons | error ≤ 5 % | 5–10 % | > 10 % | largest |', '| --- | ---: | ---: | ---: | ---: | ---: |');
for (const [rule, list] of Object.entries(byRule).sort()) {
  const e = list.map(r => r.rate_error);
  L.push(`| ${rule} | ${list.length} | ${e.filter(x => x <= 0.05).length} | ${e.filter(x => x > 0.05 && x <= 0.1).length} | ${e.filter(x => x > 0.1).length} | ${pct(Math.max(...e))} |`);
}
const vol = byRule.volley || [];
L.push('', '**Volley damage split (CoH3 ÷ game damage per shot):** ' + ['1', '1–2', '2–4', '> 4'].map((k, i) => `${k}: ${vol.filter(r => [r.multiplier <= 1, r.multiplier > 1 && r.multiplier <= 2, r.multiplier > 2 && r.multiplier <= 4, r.multiplier > 4][i]).length}`).join(' · '));
const art = byRule.artillery || [];
L.push('', '**Artillery reload turns:** ' + [0, 1, 2, 3, 4].map(t => `${t}: ${art.filter(r => r.reload_turns === t).length}`).join(' · ') +
  ` · more: ${art.filter(r => r.reload_turns > 4).length}`);

for (const race of RACES) {
  const mine = rows.filter(r => r.race === race);
  if (!mine.length) continue;
  L.push('', `## ${race}`, '', '| Weapon | subcategory | class | CoH3 damage | raw | rule | × | shots | damage | reload | acc | error |',
    '| --- | --- | --- | ---: | --- | --- | ---: | --- | --- | ---: | --- | ---: |');
  for (const r of mine.sort((a, b) => a.category.localeCompare(b.category) || a.id.localeCompare(b.id))) {
    L.push(`| ${r.id} | ${r.category} | ${r.class} | ${r.damage} | ${b3(r.raw)} | ${r.rule} | ${r.multiplier} | ${b3(r.shots_per_turn)} | ${b3(r.damage_per_shot)} | ${r.reload_turns} | ${b3(r.accuracy_scale)} | ${pct(r.rate_error)} |`);
  }
}
fs.writeFileSync(path.join(root, 'reports/fire-rate.md'), L.join('\n') + '\n');
console.log(`${rows.length} weapons → reports/fire-rate.md, reports/fire-rate.json`);
