// Runs the fire-rate conversion over every CoH3 weapon of the four factions + common and writes a review report.
// usage: node tools/import-coh3/fire-rate-report.js   → reports/fire-rate.md, reports/fire-rate.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RACES } from '../coh3/fetch.js';
import { records } from '../coh3/census.js';
import { fireRate } from './fire-rate.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'data/balance/fire-rate.json'), 'utf8'));
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/source/coh3/SOURCE.json'), 'utf8'));

const rows = [];
for (const race of RACES) {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/source/coh3/weapon', `${race}.json`), 'utf8'));
  for (const { path: p, rec } of records(data)) {
    const category = p[p.length - 2] ?? p[0];
    if (cfg.skip_categories.some(s => p.includes(s)) || p[0] === 'campaign') continue;
    const bag = rec.weapon_bag;
    rows.push({ race, id: p[p.length - 1], category, class: bag.weapon_class ?? '', damage: ((bag.damage?.min ?? 0) + (bag.damage?.max ?? 0)) / 2,
      ...fireRate(bag, category, cfg) });
  }
}

fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
fs.writeFileSync(path.join(root, 'reports/fire-rate.json'), JSON.stringify({ source: source.commit, config: cfg, weapons: rows }, null, 1) + '\n');

const b3 = o => cfg.bands.map(b => o[b] ?? '—').join(' / ');
const L = ['# Fire rate report', '',
  `CoH3 weapons (coh3-data \`${source.commit.slice(0, 8)}\`) converted to whole shots per turn (${cfg.window_seconds} s fire window).`,
  'Generated by `node tools/import-coh3/fire-rate-report.js`; rule in `tools/import-coh3/fire-rate.js`, settings in `data/balance/fire-rate.json`.', '',
  '- **raw**: CoH3 sustained shots in the fire window (bullets for burst weapons), per band near / mid / far.',
  '- **shots**: whole shots per turn used by the game.',
  '- **damage**: damage per shot used by the game; for single-shot weapons it is CoH3 damage × raw, so damage per turn keeps the CoH3 rate.',
  '- **rule**: `single` = single-shot category, `auto` = slower than one shot per turn, so treated as single-shot,\n  `per use` = grenade or mine (one shot per use, CoH3 damage).', ''];

const byCat = {};
for (const r of rows) (byCat[r.category] ??= []).push(r);
L.push('## Summary by subcategory', '', '| Subcategory | weapons | single-shot | median raw near | median shots near |', '| --- | ---: | ---: | ---: | ---: |');
const med = a => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : 0; };
for (const [cat, list] of Object.entries(byCat).sort()) {
  L.push(`| ${cat} | ${list.length} | ${list.filter(r => r.single_shot || r.auto_single_shot).length} | ${med(list.map(r => r.raw.near ?? 0))} | ${med(list.map(r => r.shots_per_turn.near))} |`);
}
for (const race of RACES) {
  const mine = rows.filter(r => r.race === race);
  if (!mine.length) continue;
  L.push('', `## ${race}`, '', '| Weapon | subcategory | class | CoH3 damage | raw | shots | damage | rule |', '| --- | --- | --- | ---: | --- | --- | --- | --- |');
  for (const r of mine.sort((a, b) => a.category.localeCompare(b.category) || a.id.localeCompare(b.id))) {
    const rule = r.per_use ? 'per use' : r.single_shot ? 'single' : r.auto_single_shot ? 'auto' : '';
    L.push(`| ${r.id} | ${r.category} | ${r.class} | ${r.damage} | ${b3(r.raw)} | ${b3(r.shots_per_turn)} | ${b3(r.damage_per_shot)} | ${rule} |`);
  }
}
fs.writeFileSync(path.join(root, 'reports/fire-rate.md'), L.join('\n') + '\n');
console.log(`${rows.length} weapons → reports/fire-rate.md, reports/fire-rate.json`);
